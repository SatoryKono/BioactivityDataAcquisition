def _pipeline_schema(pipeline_name: str) -> pa.Schema:
    for config in PIPELINE_CONFIGS:
        if config.pipeline_name == pipeline_name:
            assert config.silver_schema is not None
            return config.silver_schema
    raise KeyError(f"Unknown pipeline: {pipeline_name}")


def _expected_type(
    expected_fields: list[tuple[str, pa.DataType]], field_name: str
) -> pa.DataType:
    for name, dtype in expected_fields:
        if name == field_name:
            return dtype
    raise KeyError(f"Unknown field {field_name}")


def _invalid_value(expected_type: pa.DataType) -> object:
    if expected_type == pa.string():
        return 123
    if expected_type == pa.int64():
        return "not-an-int"
    if expected_type == pa.float64():
        return "not-a-float"
    if expected_type == pa.bool_():
        return "not-a-bool"
    if isinstance(expected_type, pa.ListType):
        return "not-a-list"
    raise AssertionError(f"Unhandled type {expected_type}")


def _valid_value(expected_type: pa.DataType) -> object:
    if expected_type == pa.string():
        return "id"
    if expected_type == pa.int64():
        return 1
    if expected_type == pa.float64():
        return 1.0
    if expected_type == pa.bool_():
        return True
    if isinstance(expected_type, pa.ListType):
        return []
    raise AssertionError(f"Unhandled type {expected_type}")


def _base_record(schema: pa.Schema) -> dict[str, object]:
    record: dict[str, object] = {
        "entity_id": "entity_1",
        "content_hash": "hash_1",
        "_run_id": "run_1",
        "_run_type": "incremental",
        "_source_batch_id": "batch_1",
        "_ingestion_ts": "2024-01-01T00:00:00Z",
    }
    if "_source" in schema.names:
        record["_source"] = "source"
    if "_index" in schema.names:
        record["_index"] = 0
    if "_lookup_method" in schema.names:
        record["_lookup_method"] = "direct"
    if "_original_id" in schema.names:
        record["_original_id"] = "orig"
    return record


