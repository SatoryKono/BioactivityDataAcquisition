def test_preserves_foreign_hooks_and_untouched_reference_callback(fixture_installation):
    repo, hooks, _ = fixture_installation
    original = b"#!/bin/sh\n# foreign callback\nexit 0\n"
    reference = b"#!/bin/sh\n# reference transaction fixture\n"
    (hooks / "pre-commit").write_bytes(original)
    (hooks / "pre-commit").chmod(0o755)
    (hooks / "reference-transaction").write_bytes(reference)
    assert installer.install(repo, Path(sys.executable))["status"] == "PASS"
    state = installer._state(hooks)
    assert state["hooks"]["pre-commit"]["chain_foreign"] is True
    assert (hooks / state["hooks"]["pre-commit"]["backup"]).read_bytes() == original
    assert (hooks / "reference-transaction").read_bytes() == reference
    installer.rollback(repo)
    assert (hooks / "pre-commit").read_bytes() == original
    assert not (hooks / "pre-push").exists()
    assert (hooks / "reference-transaction").read_bytes() == reference


def test_matching_installation_is_idempotent(fixture_installation):
    repo, hooks, _ = fixture_installation
    first = installer.install(repo, Path(sys.executable))
    before = {
        path.name: path.read_bytes() for path in hooks.iterdir() if path.is_file()
    }
    assert installer.install(repo, Path(sys.executable)) == first
    assert {
        path.name: path.read_bytes() for path in hooks.iterdir() if path.is_file()
    } == before


