@pytest.mark.parametrize("linked", [False, True])
def test_real_owned_hooks_protocol_and_foreign_callback_once(
    tmp_path, monkeypatch, linked
):
    """Only private fixture callbacks execute; deployment bundle is not a checkout."""
    shell = hook_runtime.git_shell()
    if shell is None:
        pytest.skip("Git shell unavailable")
    repo = tmp_path / "fixture with spaces"
    repo.mkdir()
    disabled = repo / "disabled"
    disabled.mkdir()
    env = dict(os.environ, PRE_COMMIT_HOME=str(repo / "cache"))
    for key in ("GIT_DIR", "GIT_WORK_TREE", "GIT_COMMON_DIR", "GIT_INDEX_FILE"):
        env.pop(key, None)

    def git(*args):
        return (
            subprocess.check_output(
                [
                    "git",
                    "-c",
                    f"core.hooksPath={disabled}",
                    "-c",
                    "user.name=Fixture",
                    "-c",
                    "user.email=fixture@example.invalid",
                    *args,
                ],
                cwd=repo,
                env=env,
                timeout=10,
            )
            .decode()
            .strip()
        )

    git("init")
    registry = repo / "configs/quality/agent_guard_budget_surfaces.json"
    registry.parent.mkdir(parents=True)
    registry.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "owner": "fixture",
                "surfaces": [{"pattern": "configs/*budget*.json", "kind": "budget"}],
            }
        )
    )
    config = {
        "repos": [
            {
                "repo": "local",
                "hooks": [
                    {
                        "id": "fixture",
                        "name": "fixture",
                        "language": "system",
                        "entry": f"\"{sys.executable}\" -c \"open('framework-runs.txt','a').write('x')\"",
                        "always_run": True,
                        "pass_filenames": False,
                    }
                ],
            }
        ]
    }
    (repo / ".pre-commit-config.yaml").write_text(json.dumps(config))
    (repo / "fixture.txt").write_text("initial")
    git("add", ".")
    git("commit", "-m", "fixture")
    sha = git("rev-parse", "HEAD")
    git("update-ref", "refs/remotes/origin/main", sha)
    if linked:
        # This tiny synthetic fixture has no tracked BioETL source or env files.
        # It is not a checkout/worktree of the user's project repository.
        destination = tmp_path / "linked fixture"
        git("worktree", "add", "--detach", str(destination), sha)
        repo = destination
        env["PRE_COMMIT_HOME"] = str(repo / "cache")
    common, hooks = installer.locations(repo)
    if linked:
        git("config", "core.hooksPath", str(common / "custom-hooks"))
        common, hooks = installer.locations(repo)
        assert hooks == common / "custom-hooks"
    hooks.mkdir(exist_ok=True)
    (hooks / "pre-commit").write_text(
        f"#!{Path(sys.executable).as_posix()}\nopen('foreign-runs.txt', 'a').write('x')\n"
    )
    (hooks / "pre-commit").chmod(0o755)
    cache = repo / "cache"
    cache.mkdir()
    with closing(sqlite3.connect(cache / "db.db")) as connection, connection:
        connection.execute("CREATE TABLE repos (repo TEXT, ref TEXT, path TEXT)")
    bundle = common / "fixture-deployment"
    files = {}
    for module in installer.MODULES:
        relative = f"scripts/engineering/repo/{module}.py"
        files[relative] = (
            Path(installer.__file__).with_name(module + ".py").read_bytes()
        )
    for package in ("scripts", "scripts/engineering", "scripts/engineering/repo"):
        files[package + "/__init__.py"] = b""
    for relative, content in files.items():
        target = bundle / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    (bundle / "manifest.json").write_text(
        json.dumps(
            {
                "version": 1,
                "files": {
                    name: installer._hash(content) for name, content in files.items()
                },
            }
        )
    )
    monkeypatch.setattr(installer, "_bundle", lambda *args: (bundle, sha))
    report = installer.install(repo, Path(sys.executable), pre_commit_home=cache)
    env.pop("PRE_COMMIT_HOME", None)
    env["PRE_COMMIT_HOME"] = str(repo / "ambient-unprepared-cache")
    assert report["status"] == "PASS"
    assert report["effective_hooks_path"] == str(hooks)
    assert report["execution_status"] == "NOT_TESTED"
    (repo / "fixture.txt").write_text("staged change")
    git("add", "fixture.txt")
    message = repo / "message.txt"
    message.write_text("fixture commit\n")
    for kind, args, payload in (
        ("pre-commit", [], b""),
        ("commit-msg", [str(message)], b""),
        (
            "pre-push",
            ["origin", "fixture"],
            f"refs/heads/main {sha} refs/heads/main {'0' * 40}\n".encode(),
        ),
    ):
        if kind == "pre-push":
            git("commit", "-m", "fixture change")
            tip = git("rev-parse", "HEAD")
            payload = f"refs/heads/main {tip} refs/heads/main {sha}\n".encode()
        result = subprocess.run(
            [shell, str(hooks / kind), *args],
            input=payload,
            cwd=repo,
            env=env,
            capture_output=True,
            timeout=45,
        )
        assert result.returncode == 0, (kind, result.stderr.decode(errors="replace"))
    assert (repo / "foreign-runs.txt").read_text() == "x"
    assert (repo / "framework-runs.txt").read_text() == "xxx"
    (repo / "fixture.txt").write_text("Git dispatch qualification")
    git("add", "fixture.txt")
    dispatched = subprocess.run(
        [
            "git",
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "commit",
            "-m",
            "fixture managed dispatch",
        ],
        cwd=repo,
        env=env,
        capture_output=True,
        timeout=90,
    )
    assert dispatched.returncode == 0, dispatched.stderr.decode(errors="replace")
    assert (repo / "foreign-runs.txt").read_text() == "xx"
    assert (repo / "framework-runs.txt").read_text() == "xxxxx"


def test_cache_selection_is_pinned_and_requires_explicit_upgrade(
    fixture_installation, monkeypatch
):
    repo, hooks, _ = fixture_installation
    cache = repo / "prepared cache"
    monkeypatch.setenv("PRE_COMMIT_HOME", str(cache))
    result = installer.install(repo, Path(sys.executable))
    assert result["pre_commit_home"] == str(cache.resolve())
    monkeypatch.delenv("PRE_COMMIT_HOME")
    assert installer.inspect_installation(repo)["pre_commit_home"] == str(
        cache.resolve()
    )
    assert (
        installer.install(repo, Path(sys.executable), pre_commit_home=cache)["status"]
        == "PASS"
    )
    assert (
        installer.install(repo, Path(sys.executable), pre_commit_home=repo / "other")[
            "reason"
        ]
        == "explicit_upgrade_required"
    )
    assert installer._state(hooks)["pre_commit_home"] == str(cache.resolve())


