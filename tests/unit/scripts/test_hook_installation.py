def test_later_owner_edit_blocks_reinstall_and_whole_rollback(fixture_installation):
    repo, hooks, _ = fixture_installation
    installer.install(repo, Path(sys.executable))
    untouched = (hooks / "pre-commit").read_bytes()
    (hooks / "commit-msg").write_bytes(b"later owner")
    assert installer.inspect_installation(repo)["status"] == "ERROR"
    with pytest.raises(ValueError, match="changed"):
        installer.install(repo, Path(sys.executable))
    with pytest.raises(ValueError, match="changed"):
        installer.rollback(repo)
    assert (hooks / "pre-commit").read_bytes() == untouched
    assert (hooks / "commit-msg").read_bytes() == b"later owner"


